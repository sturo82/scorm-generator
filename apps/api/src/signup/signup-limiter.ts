/**
 * Limitatore a finestra scorrevole in memoria, per proteggere la registrazione pubblica da abusi
 * (invii di email a indirizzi altrui, riempimento di account). È per istanza: con più istanze il
 * limite effettivo è un multiplo, per questo Manager applica a sua volta un proprio limite.
 */
export class SlidingWindowLimiter {
  private readonly hits = new Map<string, number[]>();

  constructor(
    private readonly limit: number,
    private readonly windowMs: number,
  ) {}

  /** True se la richiesta è consentita (e la conta); false se il limite è superato. */
  allow(key: string, now = Date.now()): boolean {
    const recent = (this.hits.get(key) ?? []).filter((t) => now - t < this.windowMs);
    if (recent.length >= this.limit) {
      this.hits.set(key, recent);
      return false;
    }
    recent.push(now);
    this.hits.set(key, recent);
    if (this.hits.size > 10_000) this.prune(now);
    return true;
  }

  private prune(now: number): void {
    for (const [k, v] of this.hits) {
      if (v.every((t) => now - t >= this.windowMs)) this.hits.delete(k);
    }
  }
}
